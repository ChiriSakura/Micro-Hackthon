"""User-owned reference libraries, copied and hashed before any agent runs.

Plugins are trusted Python supplied by the user, never generated by an agent.
The agents receive text, not tools capable of writing reference files.
"""
from __future__ import annotations

import hashlib
import importlib.util
import json
import sys
from pathlib import Path


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def save(path: Path, data) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + '.tmp')
    temporary.write_text(json.dumps(data, indent=2, ensure_ascii=False) + '\n')
    temporary.replace(path)


class Library:
    def __init__(self, manifest: Path, workspace: Path):
        self.manifest = manifest.resolve()
        self.root = workspace / 'references'
        self.root.mkdir(parents=True, exist_ok=False)
        spec = json.loads(self.manifest.read_text())
        if spec.get('version') != 1:
            raise ValueError('Unsupported library manifest version')
        self.algorithms = spec['algorithms']
        self.files = {}
        declarations = {f'algorithm:{k}': v['source'] for k, v in self.algorithms.items()}
        declarations.update({f'template:{k}': v for k, v in spec['hardware_templates'].items()})
        for index, (key, relative) in enumerate(declarations.items()):
            original = (self.manifest.parent / relative).resolve(strict=True)
            if not original.is_file():
                raise ValueError(f'Library entry must be a regular file: {original}')
            copy = self.root / f'{index:03d}{original.suffix}'
            copy.write_bytes(original.read_bytes())
            copy.chmod(0o444)
            self.files[key] = {'original': str(original), 'snapshot': str(copy), 'sha256': digest(copy)}
        self.manifest_hash = digest(self.manifest)
        save(workspace / 'library_manifest.json', {'manifest': str(self.manifest),
             'manifest_sha256': self.manifest_hash, 'files': self.files})

    def check(self) -> None:
        if digest(self.manifest) != self.manifest_hash:
            raise RuntimeError('Reference library manifest changed during the run')
        for value in self.files.values():
            for key in ('original', 'snapshot'):
                if digest(Path(value[key])) != value['sha256']:
                    raise RuntimeError(f'Reference library changed: {value[key]}')

    def algorithm(self, name: str):
        if name not in self.algorithms:
            raise ValueError(f'Algorithm {name!r} has no trusted executable contract; '
                             f'available: {sorted(self.algorithms)}. No fallback is allowed.')
        path = Path(self.files[f'algorithm:{name}']['snapshot'])
        spec = importlib.util.spec_from_file_location('fast_trusted_' + digest(path)[:16], path)
        module = importlib.util.module_from_spec(spec)
        sys.modules[spec.name] = module
        spec.loader.exec_module(module)
        return getattr(module, self.algorithms[name]['factory'])()

    def templates(self) -> dict[str, str]:
        return {key.removeprefix('template:'): Path(value['snapshot']).read_text()
                for key, value in self.files.items() if key.startswith('template:')}
